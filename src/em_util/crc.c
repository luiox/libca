u16 crc16_xmodem_fast(const void* data, usize size)
{
    u16 crc = 0;
    const u8* p = (const u8*)data;
    for (usize i = 0; i < size; i++) {
        crc = (crc << 8) ^ g_crc16_ccitt_table[((crc >> 8) ^ (u16)p[i]) & 0xFF];
    }
    return crc;
}

// CRC-16/XMODEM 朴素实现
u16 crc16_xmodem(const void* data, usize size)
{
    u16       crc = 0;
    const u8* p = (const u8*)data;
    for (usize i = 0; i < size; i++) {
        crc ^= (u16)p[i] << 8;
        for (int j = 0; j < 8; j++) {
            if (crc & 0x8000) {
                crc = (crc << 1) ^ 0x1021;
            } else {
                crc <<= 1;
            }
        }
    }
    return crc;
}

// CRC-16/YMODEM 查表实现
u16 crc16_ymodem_fast(const void* data, usize size)
{
    return crc16_xmodem_fast(data, size);
}

// CRC-16/YMODEM 朴素实现
u16 crc16_ymodem(const void* data, usize size)
{
    return crc16_xmodem(data, size);
}

