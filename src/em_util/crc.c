u16 crc16_modbus_fast(const void* data, usize size)
{
    u8  crchi = 0xff;
    u8  crclo = 0xff;
    u16 index;
    u8* p = (u8*)(data);
    while (size--) {
        index = crclo ^ *p++;
        crclo = crchi ^ g_crc16_modbus_table_high[index];
        crchi = g_crc16_modbus_table_low[index];
    }
    return (crchi << 8 | crclo);
}

// CRC-16/MODBUS 朴素实现
u16 crc16_modbus(const void* data, usize size)
{
    u16 crc = 0xFFFF;
    const u8* p = (const u8*)data;
    for (usize i = 0; i < size; i++) {
        crc ^= (u16)p[i];
        for (int j = 0; j < 8; j++) {
            if (crc & 0x0001) {
                crc = (crc >> 1) ^ 0xA001;
            } else {
                crc >>= 1;
            }
        }
    }
    return crc;
}

